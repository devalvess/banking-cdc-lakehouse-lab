-- Sistema legado de crédito, SEM CDC disponível. O Databricks lê via JDBC incremental
-- usando DT_ATUALIZACAO como marca d'água, e detecta deletes comparando chaves.

CREATE SCHEMA LEGADO@

CREATE TABLE LEGADO.AGENCIAS (
    CD_AGENCIA       INTEGER       NOT NULL,
    NM_AGENCIA       VARCHAR(60)   NOT NULL,
    NM_CIDADE        VARCHAR(60)   NOT NULL,
    SG_UF            CHAR(2)       NOT NULL,
    DS_REGIAO        VARCHAR(20)   NOT NULL,   -- SUDESTE | SUL | NORDESTE | ...
    DT_ATUALIZACAO   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_AGENCIAS PRIMARY KEY (CD_AGENCIA)
)@

CREATE TABLE LEGADO.CONTRATOS_CREDITO (
    ID_CONTRATO        INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 900000),
    ID_CLIENTE         INTEGER       NOT NULL,
    TP_PRODUTO         VARCHAR(30)   NOT NULL,   -- CONSIGNADO | PESSOAL | VEICULO | CARTAO_ROTATIVO
    VL_CONTRATO        DECIMAL(15,2) NOT NULL,
    VL_SALDO_DEVEDOR   DECIMAL(15,2) NOT NULL,
    QT_PARCELAS        INTEGER       NOT NULL,
    QT_PARCELAS_PAGAS  INTEGER       NOT NULL DEFAULT 0,
    NR_DIAS_ATRASO     INTEGER       NOT NULL DEFAULT 0,
    DT_CONTRATACAO     DATE          NOT NULL,
    DT_ATUALIZACAO     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_CONTRATOS PRIMARY KEY (ID_CONTRATO)
)@

-- Índice na coluna de marca d'água: sem ele, cada carga incremental faria varredura completa
-- da tabela no legado.
CREATE INDEX LEGADO.IX_CONTRATOS_DT_ATUALIZACAO ON LEGADO.CONTRATOS_CREDITO (DT_ATUALIZACAO)@
