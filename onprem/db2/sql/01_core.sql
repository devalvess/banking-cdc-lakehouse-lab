-- Core bancário (sistema transacional). Estas tabelas entram em CDC (ver 04_cdc.sql).

CREATE SCHEMA CORE@

CREATE TABLE CORE.CLIENTES (
    ID_CLIENTE       INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    NR_CPF           CHAR(11)      NOT NULL,
    NM_CLIENTE       VARCHAR(120)  NOT NULL,
    DS_EMAIL         VARCHAR(120),
    NR_TELEFONE      VARCHAR(20),
    DT_NASCIMENTO    DATE,
    NM_CIDADE        VARCHAR(60),
    SG_UF            CHAR(2),
    VL_RENDA_MENSAL  DECIMAL(15,2),
    CD_AGENCIA       INTEGER       NOT NULL,
    DT_CADASTRO      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    DT_ATUALIZACAO   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE)
)@

CREATE TABLE CORE.CONTAS (
    ID_CONTA         INTEGER       NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 50000),
    ID_CLIENTE       INTEGER       NOT NULL,
    CD_AGENCIA       INTEGER       NOT NULL,
    TP_CONTA         VARCHAR(20)   NOT NULL,   -- CORRENTE | POUPANCA | SALARIO
    VL_SALDO         DECIMAL(15,2) NOT NULL DEFAULT 0,
    ST_CONTA         VARCHAR(10)   NOT NULL DEFAULT 'ATIVA',
    DT_ABERTURA      DATE          NOT NULL DEFAULT CURRENT DATE,
    DT_ATUALIZACAO   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_CONTAS PRIMARY KEY (ID_CONTA)
)@

CREATE INDEX CORE.IX_CONTAS_CLIENTE ON CORE.CONTAS (ID_CLIENTE)@

CREATE TABLE CORE.TRANSACOES (
    ID_TRANSACAO     BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_CONTA         INTEGER       NOT NULL,
    TP_TRANSACAO     VARCHAR(20)   NOT NULL,   -- PIX_ENVIADO | PIX_RECEBIDO | DEBITO | SALARIO | TARIFA
    VL_TRANSACAO     DECIMAL(15,2) NOT NULL,
    DT_TRANSACAO     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_TRANSACOES PRIMARY KEY (ID_TRANSACAO)
)@

CREATE INDEX CORE.IX_TRANSACOES_CONTA ON CORE.TRANSACOES (ID_CONTA)@
