-- Ativa os registros de CDC ainda inativos enviando o sinal CAPSTART ao ASN Capture.
-- (No SQL Replication clássico quem envia este sinal é o programa Apply; aqui o consumidor é o Debezium.)
INSERT INTO ASNCDC.IBMSNAP_SIGNAL (SIGNAL_TIME, SIGNAL_TYPE, SIGNAL_SUBTYPE, SIGNAL_INPUT_IN, SIGNAL_STATE)
SELECT CURRENT TIMESTAMP, 'CMD', 'CAPSTART', P.MAP_ID, 'P'
  FROM ASNCDC.IBMSNAP_PRUNCNTL P
  JOIN ASNCDC.IBMSNAP_REGISTER R
    ON R.SOURCE_OWNER = P.SOURCE_OWNER AND R.SOURCE_TABLE = P.SOURCE_TABLE
 WHERE R.GLOBAL_RECORD = 'N' AND R.STATE = 'I';
